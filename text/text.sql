-- ==============================================
-- 第一个数据库：班级学生信息库
-- ==============================================
CREATE DATABASE IF NOT EXISTS class_info;
USE class_info;

-- 创建一班表
CREATE TABLE IF NOT EXISTS class_one (
    id INT AUTO_INCREMENT PRIMARY KEY,  -- 自增主键
    student_name VARCHAR(50) NOT NULL,  -- 学生姓名
    height DECIMAL(5,2) NOT NULL,      -- 身高（单位：米）
    weight DECIMAL(5,2) NOT NULL,      -- 体重（单位：公斤）
    hobby VARCHAR(100) NOT NULL        -- 爱好
);

-- 创建二班表
CREATE TABLE IF NOT EXISTS class_two (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_name VARCHAR(50) NOT NULL,
    height DECIMAL(5,2) NOT NULL,
    weight DECIMAL(5,2) NOT NULL,
    hobby VARCHAR(100) NOT NULL
);

-- 创建三班表
CREATE TABLE IF NOT EXISTS class_three (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_name VARCHAR(50) NOT NULL,
    height DECIMAL(5,2) NOT NULL,
    weight DECIMAL(5,2) NOT NULL,
    hobby VARCHAR(100) NOT NULL
);

-- ==============================================
-- 第二个数据库：编程语言信息库
-- ==============================================
CREATE DATABASE IF NOT EXISTS language_info;
USE language_info;

-- 创建C++表
CREATE TABLE IF NOT EXISTS cpp_language (
    id INT AUTO_INCREMENT PRIMARY KEY,
    feature VARCHAR(100) NOT NULL,     -- 语言特性
    usage_scenario VARCHAR(200) NOT NULL,  -- 使用场景
    difficulty VARCHAR(20) NOT NULL    -- 学习难度
);

-- 创建GO表
CREATE TABLE IF NOT EXISTS go_language (
    id INT AUTO_INCREMENT PRIMARY KEY,
    feature VARCHAR(100) NOT NULL,
    usage_scenario VARCHAR(200) NOT NULL,
    difficulty VARCHAR(20) NOT NULL
);

-- 创建Python表
CREATE TABLE IF NOT EXISTS python_language (
    id INT AUTO_INCREMENT PRIMARY KEY,
    feature VARCHAR(100) NOT NULL,
    usage_scenario VARCHAR(200) NOT NULL,
    difficulty VARCHAR(20) NOT NULL
);


